#!/usr/bin/env python3
"""Generate every token output from tokens.json. Standard library only.

    python3 replica/design/build.py

Writes, next to tokens.json:
  tokens.css          CSS custom properties, light on :root, dark under
                      prefers-color-scheme and [data-theme="dark"]
  tailwind.preset.js  Tailwind preset (web and NativeWind) mapping roles to the vars
  tokens.ts           typed light/dark objects for React Native StyleSheet use
  tokens.dark.json    the dark palette with the same pairs, for contrast.py

Edit tokens.json, never the generated files.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
HEADER = "Generated by build.py from tokens.json. Do not edit."


def public(d):
    return {k: v for k, v in d.items() if not k.startswith("_")}


def css(t):
    light, dark = t["color"], t["color_dark"]
    out = ["/* %s */" % HEADER,
           "/* [data-theme] works on any element: the tracker (S12) is always dark. */",
           ":root, [data-theme=\"light\"] {"]
    out += ["  --color-%s: %s;" % (k, v) for k, v in light.items()]
    out.append("  --font-sans: %s;" % t["font"]["sans"])
    out.append("  --font-mono: %s;" % t["font"]["mono"])
    for name, s in t["type"].items():
        out.append("  --text-%s: %dpx;" % (name, s["size"]))
        out.append("  --leading-%s: %dpx;" % (name, s["line"]))
        out.append("  --weight-%s: %d;" % (name, s["weight"]))
    for i, px in enumerate(t["space"]):
        out.append("  --space-%d: %dpx;" % (i, px))
    for k, v in t["radius"].items():
        out.append("  --radius-%s: %dpx;" % (k, v))
    for k, v in t["shadow"].items():
        out.append("  --shadow-%s: %s;" % (k, v))
    for k, v in public(t["motion"]).items():
        out.append("  --motion-%s: %s;" % (k, v))
    for k, v in t["layout"].items():
        if isinstance(v, int):
            out.append("  --layout-%s: %dpx;" % (k.replace("_", "-"), v))
    out.append("  color-scheme: light;")
    out.append("}")
    dark_vars = ["    --color-%s: %s;" % (k, v) for k, v in dark.items()]
    out.append("@media (prefers-color-scheme: dark) {")
    out.append("  :root:not([data-theme=\"light\"]) {")
    out += dark_vars
    out.append("    color-scheme: dark;")
    out.append("  }")
    out.append("}")
    out.append(":root[data-theme=\"dark\"], [data-theme=\"dark\"] {")
    out += [v[2:] for v in dark_vars]
    out.append("  color-scheme: dark;")
    out.append("}")
    out.append("@media (prefers-reduced-motion: reduce) {")
    out.append("  :root { --motion-fast: 0ms; --motion-base: 0ms; --motion-slow: 0ms; }")
    out.append("}")
    return "\n".join(out) + "\n"


def tailwind(t):
    colors = {k: "var(--color-%s)" % k for k in t["color"]}
    font_size = {k: ["var(--text-%s)" % k, {"lineHeight": "var(--leading-%s)" % k,
                                             "fontWeight": "var(--weight-%s)" % k}]
                 for k in t["type"]}
    spacing = {str(i): "var(--space-%d)" % i for i in range(len(t["space"]))}
    radius = {k: "var(--radius-%s)" % k for k in t["radius"]}
    shadow = {k: "var(--shadow-%s)" % k for k in t["shadow"]}
    screens = {k: "%dpx" % v for k, v in t["layout"]["breakpoints"].items()}
    preset = {
        "darkMode": ["variant", ["@media (prefers-color-scheme: dark) { &:not([data-theme=light] *) }",
                                 "&:is([data-theme=dark] *)"]],
        "theme": {
            "screens": screens,
            "colors": dict(colors, transparent="transparent", current="currentColor"),
            "fontFamily": {"sans": ["var(--font-sans)"], "mono": ["var(--font-mono)"]},
            "fontSize": font_size,
            "spacing": spacing,
            "borderRadius": dict(radius, none="0"),
            "boxShadow": dict(shadow, none="none"),
            "extend": {
                "transitionDuration": {"fast": "var(--motion-fast)", "base": "var(--motion-base)",
                                       "slow": "var(--motion-slow)"},
                "transitionTimingFunction": {"out": "var(--motion-ease)"},
                "minHeight": {"touch": "var(--layout-touch-min)"},
                "minWidth": {"touch": "var(--layout-touch-min)"},
                "maxWidth": {"content": "var(--layout-content-max)", "page": "var(--layout-web-content-max)"},
            },
        },
    }
    return ("// %s\n// Spacing is index-based on purpose: p-4 = 16px (space[4]), gap-2 = 8px.\n"
            "/** @type {import('tailwindcss').Config} */\nmodule.exports = %s;\n"
            % (HEADER, json.dumps(preset, indent=2)))


def ts(t):
    body = {
        "light": t["color"],
        "dark": t["color_dark"],
        "type": t["type"],
        "space": t["space"],
        "radius": t["radius"],
        "layout": t["layout"],
        "effort": public(t["effort_map"]),
        "fontFamily": "Inter",
    }
    return ("// %s\nexport const tokens = %s as const;\n\n"
            "export type ColorRole = keyof typeof tokens.light;\n"
            "export type Effort = 0 | 1 | 2 | 3 | 4 | 5;\n"
            "export type SessionType = keyof typeof tokens.effort.session_type;\n"
            "export type PaceZone = keyof typeof tokens.effort.pace_zone;\n\n"
            "export const effortOf = (type: SessionType): Effort => tokens.effort.session_type[type] as Effort;\n"
            % (HEADER, json.dumps(body, indent=2)))


def main():
    with open(os.path.join(HERE, "tokens.json"), encoding="utf-8") as fh:
        t = json.load(fh)
    missing = set(t["color"]) ^ set(t["color_dark"])
    if missing:
        raise SystemExit("light and dark palettes differ in roles: %s" % sorted(missing))
    files = {
        "tokens.css": css(t),
        "tailwind.preset.js": tailwind(t),
        "tokens.ts": ts(t),
        "tokens.dark.json": json.dumps({"_about": HEADER, "color": t["color_dark"],
                                        "pairs": t["pairs"]}, indent=2) + "\n",
    }
    # the app imports the same generated file; never edit it there either
    app_tokens = os.path.join(HERE, "..", "..", "apps", "mobile", "src", "theme", "tokens.ts")
    targets = {name: os.path.join(HERE, name) for name in files}
    if os.path.isdir(os.path.join(HERE, "..", "..", "apps", "mobile")):
        os.makedirs(os.path.dirname(app_tokens), exist_ok=True)
        targets["apps/mobile/src/theme/tokens.ts"] = app_tokens
        files["apps/mobile/src/theme/tokens.ts"] = files["tokens.ts"]
    for name, content in files.items():
        with open(targets[name], "w", encoding="utf-8") as fh:
            fh.write(content)
        print("wrote", name)


if __name__ == "__main__":
    main()
